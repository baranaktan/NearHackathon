import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  deriveInvoice,
  deriveStealth,
  encodeMetaAddress,
  encodeViewingKey,
  explorerAccountUrl,
  explorerTxUrl,
  formatNear,
  generateMnemonic,
  keysFromMnemonic,
  NearRpc,
  NETWORKS,
  parseNear,
  PerdeClient,
  recoverSpendScalar,
  ScalarSigner,
  sendActions,
  transfer,
  verifyReceipt,
} from '../src/index.js';
import { type Funder, getFunder, waitFor } from './testnetFunder.js';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..', '..', '..');
const EVIDENCE = join(ROOT, 'evidence', 'core-testnet-run.md');
const DEPLOYMENT = join(ROOT, 'deployments', 'testnet.json');

const rpc = new NearRpc({ urls: NETWORKS.testnet.rpcUrls });
const log: string[] = [];
const tx = (label: string, hash: string): void => {
  log.push(`- ${label}: [\`${hash}\`](${explorerTxUrl('testnet', hash)})`);
};
const note = (line: string): void => {
  log.push(line);
};
const near = (y: bigint): string => `${formatNear(y)} NEAR`;
const settle = (): Promise<void> => new Promise((r) => setTimeout(r, 2500));

function writeEvidence(funder: Funder, sections: string[]): void {
  mkdirSync(dirname(EVIDENCE), { recursive: true });
  const header = [
    '# @perde/core — live testnet run',
    '',
    `Generated by \`npm run test:testnet\` (packages/core/test/core.testnet.test.ts) at ${new Date().toISOString()}.`,
    'No private keys are recorded here. Every stealth key below was derived from a fresh random 12-word mnemonic that existed only in memory.',
    '',
    '## Funding account (testnet faucet)',
    '',
    `- account: [${funder.accountId}](${explorerAccountUrl('testnet', funder.accountId)})`,
    funder.faucetMs !== undefined
      ? `- created ${funder.createdNow ? 'in this run' : 'by an earlier run of this test (cached, reused while it holds ≥ 3 NEAR)'} via \`createFaucetAccount\` → \`POST https://helper.nearprotocol.com/account\`: ${funder.faucetMs} ms until visible over RPC, starting balance ${funder.faucetBalance === undefined ? '?' : near(funder.faucetBalance)}, rate-limit headers ${JSON.stringify(funder.rateLimit)}${funder.txHash ? `, faucet tx [\`${funder.txHash}\`](${explorerTxUrl('testnet', funder.txHash)})` : ''}`
      : '- reused from an earlier run in this checkout (faucet allows ~10 accounts / 12 h per IP)',
    '',
  ];
  writeFileSync(EVIDENCE, [...header, ...sections].join('\n') + '\n');
}

describe('testnet: a scalar-derived key controls an implicit account', () => {
  it('faucet → transfer to stealth → balance → claim back (transfer & deleteAccount) → contract path', async () => {
    const funder = await getFunder(rpc);
    const client = new PerdeClient({ network: 'testnet', rpcUrls: NETWORKS.testnet.rpcUrls });

    // --- 1. Plain Transfer to a stealth implicit account (no contract involved) ---
    note('## 1. Plain transfer → stealth implicit account → sweep with ScalarSigner (no contract)');
    note('');
    const alice = keysFromMnemonic(generateMnemonic());
    const meta = encodeMetaAddress(alice);
    const stealth = deriveStealth(meta);
    note(`- recipient meta-address: \`${meta}\``);
    note(`- stealth account (hex(P)): [${stealth.stealthAccountId}](${explorerAccountUrl('testnet', stealth.stealthAccountId)})`);
    const amount = parseNear('0.5');
    const funderBefore = await rpc.getBalance(funder.accountId);
    const fund = await sendActions({ rpc, signer: funder.signer, signerId: funder.accountId, receiverId: stealth.stealthAccountId, actions: [transfer(amount)] });
    expect(fund.success).toBe(true);
    tx('funding Transfer (creates the implicit account)', fund.hash);
    const stealthBalance = await waitFor(() => rpc.getBalance(stealth.stealthAccountId), (b) => b > 0n);
    expect(stealthBalance).toBe(amount);
    await settle();
    const funderAfter = await rpc.getBalance(funder.accountId);
    note(`- stealth balance after funding: ${near(stealthBalance)} (full amount arrived)`);
    note(`- sender paid ${near(funderBefore - funderAfter - amount)} on top of the amount; tx tokens_burnt = ${near(fund.tokensBurnt)}, gas_burnt = ${fund.gasBurnt} (includes the protocol's 0.007 NEAR account_creation_charge for a new implicit account)`);

    const p = recoverSpendScalar(alice, stealth);
    const signer = new ScalarSigner(p);
    expect(signer.accountId).toBe(stealth.stealthAccountId);
    const accessKey = await rpc.getAccessKey(stealth.stealthAccountId, signer.publicKey);
    expect(accessKey.permission).toBe('FullAccess');
    note(`- the only access key of the stealth account is P (FullAccess), nonce ${accessKey.nonce}`);

    const claim1 = await client.claim(alice, stealth, funder.accountId);
    expect(claim1.outcome.success).toBe(true);
    tx('claim (Transfer balance − reserve, signed with the stealth scalar)', claim1.txHash);
    await settle();
    const dust = await rpc.getBalance(stealth.stealthAccountId);
    note(`- claim moved ${near(claim1.amountYocto)}; reserve kept ${near(claim1.fee.reserve)} (gas ${claim1.fee.gas}, reserve price ${claim1.fee.reservePrice} yocto/gas); tokens burnt ${near(claim1.tokensBurnt)}; dust left after refund ${near(dust)}`);
    expect(dust).toBe(claim1.fee.reserve - claim1.tokensBurnt);

    // --- 2. Invoice account (no announcement) swept with DeleteAccount ---
    note('');
    note('## 2. Invoice #0 (derivable from the viewing key alone) → scanInvoices → claim with DeleteAccount');
    note('');
    const invoice = deriveInvoice(alice, 0);
    const fundInv = await sendActions({ rpc, signer: funder.signer, signerId: funder.accountId, receiverId: invoice.stealthAccountId, actions: [transfer(parseNear('0.2'))] });
    tx('pay invoice #0 (plain Transfer)', fundInv.hash);
    await waitFor(() => rpc.getBalance(invoice.stealthAccountId), (b) => b > 0n);
    const invoices = await client.scanInvoices(encodeViewingKey(alice), { gapLimit: 5 });
    expect(invoices.map((i) => i.index)).toEqual([0]);
    expect(invoices[0]?.balance).toBe(parseNear('0.2'));
    note(`- scanInvoices(viewing key, gapLimit 5) found invoice #0 with ${near(invoices[0]?.balance ?? 0n)}`);
    await settle(); // let the funding tx's gas refund land before measuring the beneficiary
    const destBefore = await rpc.getBalance(funder.accountId);
    const claim2 = await client.claim(alice, { invoiceIndex: 0 }, funder.accountId, { mode: 'deleteAccount' });
    tx('claim invoice #0 (DeleteAccount, beneficiary = funder)', claim2.txHash);
    await waitFor(() => rpc.accountExists(invoice.stealthAccountId), (e) => !e);
    await settle();
    const destAfter = await rpc.getBalance(funder.accountId);
    const received = destAfter - destBefore;
    note(`- DeleteAccount: beneficiary received ${near(received)} of ${near(claim2.balanceBefore)} (total cost ${near(claim2.balanceBefore - received)}; tokens burnt ${near(claim2.tokensBurnt)}); stealth account deleted, no dust left behind`);
    expect(received).toBeGreaterThan(claim2.balanceBefore - parseNear('0.001'));
    expect(received).toBeLessThanOrEqual(claim2.balanceBefore - claim2.tokensBurnt);

    // --- 3. Contract path, when deployed ---
    const sections = [...log];
    log.length = 0;
    if (existsSync(DEPLOYMENT)) {
      const { contractId } = JSON.parse(readFileSync(DEPLOYMENT, 'utf8')) as { contractId: string };
      const perde = new PerdeClient({ network: 'testnet', contractId, rpcUrls: NETWORKS.testnet.rpcUrls });
      note('');
      note(`## 3. Contract path (\`${contractId}\`): register → send → fetchAnnouncements → scan → claim, plus sendBatch`);
      note('');
      const config = await perde.getConfig();
      note(`- get_config: announce_fee ${near(config.announceFee)}, min_amount ${near(config.minAmount)}, version ${config.version}`);
      const startIndex = await perde.announcementCount();

      const bob = keysFromMnemonic(generateMnemonic());
      const reg = await perde.register(funder.signer, funder.accountId, encodeMetaAddress(bob));
      tx(`register(meta) for ${funder.accountId}`, reg.hash);
      expect(await waitFor(() => perde.getMetaAddress(funder.accountId), (m) => m !== null)).toBe(encodeMetaAddress(bob));

      const sent = await perde.send(funder.signer, funder.accountId, funder.accountId, parseNear('0.1'));
      tx('send 0.1 NEAR to the registered account name', sent.txHash);
      note(`- announcement index ${sent.announcementIndex}; receipt verifies offline: ${verifyReceipt(sent.receipt).valid}`);
      const creation = sent.outcome.raw.receipts_outcome.find((r) => r.outcome.executor_id === sent.stealthAccountId);
      note(`- send cost to the sender: deposit ${near(sent.amountYocto + config.announceFee)} + ${near(sent.outcome.tokensBurnt)} burnt (gas ${sent.outcome.gasBurnt}); of that, ${near(BigInt(creation?.outcome.tokens_burnt ?? '0'))} / ${creation?.outcome.gas_burnt ?? 0} gas was the Transfer receipt that created the stealth account (account-creation charge, paid from the sender's attached gas)`);

      const carol = keysFromMnemonic(generateMnemonic());
      const batch = await perde.sendBatch(funder.signer, funder.accountId, [
        { to: encodeMetaAddress(bob), amountYocto: parseNear('0.05') },
        { to: encodeMetaAddress(carol), amountYocto: parseNear('0.03') },
      ]);
      tx('sendBatch: 2 send actions in ONE transaction', batch.txHash);

      await settle();
      const page = await perde.fetchAnnouncements({ fromIndex: startIndex });
      expect(page.announcements.length).toBeGreaterThanOrEqual(3);
      const scanBob = await perde.scan(encodeViewingKey(bob), { fromIndex: startIndex });
      const scanCarol = await perde.scan(carol, { fromIndex: startIndex });
      expect(scanBob.payments.map((x) => x.stealthAccountId).sort()).toEqual([sent.stealthAccountId, batch.items[0]?.stealthAccountId].sort());
      expect(scanCarol.payments.map((x) => x.stealthAccountId)).toEqual([batch.items[1]?.stealthAccountId]);
      for (const pay of [...scanBob.payments, ...scanCarol.payments]) expect(pay.balance).toBe(pay.amount);
      note(`- fetchAnnouncements(from ${startIndex}) returned ${page.announcements.length}; scan(bob's viewing key) found ${scanBob.payments.length}, scan(carol) found ${scanCarol.payments.length}; live balances equal announced amounts`);

      const onChainReceipt = await perde.verifyReceipt(sent.receipt);
      expect(onChainReceipt.valid && onChainReceipt.announced).toBe(true);
      note(`- receipt verified against the on-chain announcement #${onChainReceipt.announcement?.index}`);

      const target = scanBob.payments.find((x) => x.stealthAccountId === sent.stealthAccountId);
      if (target === undefined) throw new Error('payment not found');
      const claim3 = await perde.claim(bob, target, funder.accountId);
      tx('claim the 0.1 NEAR payment (Transfer, ScalarSigner)', claim3.txHash);
      const carolPay = scanCarol.payments[0];
      if (carolPay === undefined) throw new Error('carol payment not found');
      const claim4 = await perde.claim(carol, carolPay, funder.accountId, { mode: 'deleteAccount' });
      tx('claim carol\'s batch payment (DeleteAccount)', claim4.txHash);
      expect(claim3.outcome.success && claim4.outcome.success).toBe(true);

      const unreg = await perde.unregister(funder.signer, funder.accountId);
      tx('unregister (storage refund)', unreg.hash);
    } else {
      note('');
      note('## 3. Contract path: skipped (deployments/testnet.json not present)');
    }
    writeEvidence(funder, [...sections, ...log]);
  });
});
